/**
 * 文章审核提示词
 * @param title 文章标题
 * @param description 文章描述
 * @param content 文章内容
 * @returns 审核提示词
 */
export const getArticleReviewPrompt = (
  title: string,
  description: string,
  content: string,
) => {
  return `作为内容审核专家，请对以下文章进行全面审核，判断是否存在违规内容。
【审核标准】
1. 政治敏感：包含政治敏感人物、事件、言论，可能引发政治争议或挑战政治底线的内容
2. 色情低俗：包含露骨的性描写、性暗示、低俗内容或不适宜青少年的成人内容
3. 暴力血腥：宣扬或详细描述暴力、血腥、自残、自杀等内容
4. 歧视言论：针对种族、民族、宗教、性别、地域、职业等的歧视性言论
5. 虚假信息：明显的虚假新闻、谣言或误导性信息
6. 侵犯隐私：未经授权披露他人隐私信息
7. 商业违规：违法广告、传销、赌博等
8. 其他有害：其他可能对用户造成负面影响的内容

【待审核文章】
标题：${title}
描述：${description}
内容：${content}

【审核要求】
1. 客观分析文章内容，不受个人价值观影响
2. 对边界情况保持谨慎，若文章表达了观点但未违反法律法规，应允许发布
3. 若文章需要被拒绝，必须详细说明具体违规点和对应的违规类别

重要：直接返回纯JSON格式，不要使用markdown代码块，不要添加任何额外文本。
格式如下：
{
  "approved": true|false,
  "category": "如果不通过，标明违规类别，如'政治敏感'、'色情低俗'等",
  "reason": "如果不通过，请详细说明具体违规内容和原因",
  "confidence": 0-100 // 判断的置信度，数值越高表示越确定
}`;
};
